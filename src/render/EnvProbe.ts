import * as THREE from 'three';
import { RGBELoader } from 'three/examples/jsm/loaders/RGBELoader.js';

/**
 * The environment probe: the thing the car's paint reflects.
 *
 * SINCE ISSUE #78 THERE ARE TWO OF THEM, AND THE PROCEDURAL ONE IS THE FALLBACK.
 *
 * Everything below the divider is the generated probe, unchanged, and it is
 * still what the first frame of every session is lit by. What sits on top of it
 * now is a real captured sky — a CC0 Poly Haven HDRI from `public/assets/hdri/`
 * — loaded asynchronously and swapped in when it arrives.
 *
 * The reason to do it in that order rather than simply replacing the generated
 * probe is the same reason `public/brand/` was specified as an asset SLOT in
 * PROJECT.md §3: `public/assets/` is gitignored and regenerated by
 * `scripts/fetchAssets.ts`, so a clone that has never run the fetcher, a build
 * with the directory deleted, and a player on a connection that drops the
 * request must all still get a lit scene. They do: `apply()` installs the
 * generated probe synchronously every time, and the HDRI only ever *replaces*
 * an image that was already correct. Deleting `public/assets/hdri/` returns the
 * renderer to exactly its pre-#78 behaviour, which is the guarantee that makes
 * the asset optional rather than required.
 *
 * WHAT THE CAPTURED SKY BUYS, IN ONE SENTENCE: the generated probe is a 256x128
 * analytic function — a gradient, a haze band, three sine terms and a sun disc —
 * and a `MeshStandardMaterial` integrating that over a roughness cone gets back
 * something very close to a constant. A 2048x1024 photograph of a real sky has
 * structure at every scale, so the same integral returns a different number for
 * every surface normal, and *that* is what makes clear coat and metal read as
 * clear coat and metal rather than as tinted plastic.
 *
 * THE SUN IN THE PROBE DID NOT AGREE WITH THE SUN IN THE SCENE, and this is
 * where that is fixed. `Renderer.applyAmbience` already takes care to point the
 * sky dome's disc at the key light — "so the halo, the silver lining on the
 * cloud edges and the shadows on the track all agree" — and then hands the probe
 * nothing at all. `PALETTES.day.sunAzimuth` is 205 degrees, i.e. atan2(x,z) of
 * (-0.42, ., -0.91); the day key light stands at (-220, 400, 180), which is
 * 309.3 degrees. **The reflected highlight came from 104 degrees away from the
 * light casting the shadow**, and has since the probe was written. The
 * generated probe is left as it is, because moving its sun would move every
 * highlight in every audit shot on `main` for no measured reason; the loaded
 * HDRI is scanned for its OWN brightest direction and rotated so that direction
 * lands on the key light's azimuth. Rotating the environment rather than moving
 * the light is deliberate: the shadow direction is what `probe:framing`,
 * `probe:banking` and every audit shot in the repository are laid out against,
 * and none of them should move for a reflection fix.
 *
 * This is the highest-leverage object in the whole renderer, and the reason is
 * worth stating plainly, because the first version of it got this exactly wrong.
 *
 * A `MeshStandardMaterial` computes its specular response by integrating the
 * environment over a cone whose width is set by roughness. If the environment is
 * a SMOOTH GRADIENT, that integral is — to within a few percent — the same
 * number everywhere on a curved panel. Which means the reflection term is a flat
 * wash, the diffuse term is a flat wash, and the sum of two flat washes is
 * painted plastic. That is what the previous 64x64 "bright above, dark below,
 * warm on one side" probe produced, and no amount of tuning roughness rescues
 * it, because the information simply is not in the probe.
 *
 * What makes a car look like a car is CONTRAST IN THE PROBE, specifically:
 *
 *  - A HARD HORIZON. The single most important feature. Sky is bright, ground is
 *    dark, and the line between them is sharp. As a curved flank turns past the
 *    horizon, its reflection sweeps from bright to dark across a few centimetres
 *    — that travelling light/dark boundary along a sidepod is the whole reason
 *    the shape reads as a shape. A probe without a horizon has no shape cue at
 *    all.
 *  - A SMALL, VERY BRIGHT SUN. Order 100x the sky's radiance, not 1.2x. This is
 *    what puts a compact hot highlight on the airbox and along the halo, and it
 *    only works if the probe is float — an 8-bit probe clips it to the same
 *    white as the sky and the highlight disappears into the wash.
 *  - HORIZONTAL STRUCTURE. Cloud banding by day, a ring of floodlights at night,
 *    a bright horizon haze band always. These stretch into the long streaky
 *    highlights that run the length of a real car's bodywork. They are the
 *    difference between "shiny" and "wet-looking".
 *
 * Cost: one 256x128 float image, generated once per ambience, PMREM-filtered,
 * and then it is free forever. There are no image files in this project and
 * there will not be any.
 */

export type Ambience = 'day' | 'dusk' | 'night';

/** Equirectangular probe resolution. PMREM downsamples anyway; this is plenty. */
const W = 256;
const H = 128;

interface Palette {
  /** Zenith, horizon-sky, and ground colours as linear RGB triples. */
  zenith: [number, number, number];
  horizon: [number, number, number];
  ground: [number, number, number];
  /** Sun colour and peak radiance multiplier. */
  sun: [number, number, number];
  sunPower: number;
  /** Elevation of the sun, in degrees above the horizon. */
  sunElevation: number;
  /** Azimuth of the sun, in degrees. */
  sunAzimuth: number;
  /** Strength of the bright haze band sitting on the horizon. */
  hazeBoost: number;
  /** Cloud/floodlight banding strength. */
  banding: number;
  /** Number of discrete light sources around the horizon (floodlights). */
  floodlights: number;
  /** Radiance of each floodlight. */
  floodPower: number;
  /** Colour of the floodlights. */
  floodColour: [number, number, number];
}

