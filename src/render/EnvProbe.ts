/**
 * Which CC0 Poly Haven capture each ambience reflects, dry and wet.
 *
 * The wet column is not decoration. `renderProbe` already flattens the
 * generated sun by `1 - wetness * 0.85` for a stated reason — a wet race has no
 * hard sun, and leaving one in puts a hot highlight on the car that agrees with
 * nothing else on screen. A photographed sky cannot be flattened that way
 * without destroying the structure it was loaded for, so the wet case swaps to
 * a genuinely overcast capture instead, which is the same correction made with
 * the right instrument.
 *
 * Night has no wet variant because there is no CC0 overcast-night capture in
 * the fetched set, and substituting the dry one is the honest answer rather
 * than dimming a clear sky and calling it cloud.
 */
const HDRI_FOR: Record<Ambience, { dry: string; wet: string } | null> = {
  day: { dry: 'partly_cloudy', wet: 'overcast' },
  dusk: { dry: 'sunset', wet: 'overcast' },
  /**
   * NIGHT KEEPS THE GENERATED PROBE, AND THIS IS A MEASUREMENT, NOT AN
   * OVERSIGHT.
   *
   * `hdri/night` is Poly Haven's Dikhololo Night: a genuinely beautiful RURAL
   * sky, which is to say a starfield over dark veld with no artificial light in
   * it anywhere. A Formula 1 circuit at night is the exact opposite — it is one
   * of the most intensely lit outdoor spaces there is — and the thing a car's
   * paint reflects there is not sky at all, it is two hundred metal-halide
   * lamps. The generated night probe models precisely that: `PALETTES.night`
   * carries fourteen point sources at 20x radiance in two staggered rows, and
   * its own comment explains that the ratio between a near-black dome and a
   * ring of small hot sources is what produces the hard specular streaks along
   * a floodlit car's flanks.
   *
   * Swapping that for a rural capture was tried and it is a straight
   * downgrade: it removes the only bright features in the probe and leaves the
   * cars matte. So day and dusk take the photograph, because a real sky beats
   * three sine terms, and night keeps the analytic probe, because a real sky of
   * the WRONG PLACE loses to a deliberate model of the right one. There is no
   * CC0 capture of a floodlit stadium in the fetched set; if one is ever added
   * this is the one line that changes.
   */
  night: null,
};

/**
 * Scene environment intensity per ambience.
 *
 * A captured sky carries absolute radiance and a generated one carries whatever
 * the palette's author typed, so the two do not arrive at the same exposure and
 * pretending they do is how an HDRI lands looking either washed out or black.
 * These are set from measurement — `npm run probe:grade`, the frame's median
 * luma and RMS contrast against the reference frame for the same conditions —
 * and not from looking at it. See PROJECT.md section 6 for the numbers.
 */
const HDRI_INTENSITY: Record<Ambience, number> = {
  day: 1.0,
  dusk: 1.0,
  night: 1.0,
};

interface LoadedHdri {
  target: THREE.WebGLRenderTarget;
  /** Azimuth of the capture's own brightest direction, radians, or null. */
  sunAzimuth: number | null;
}

/**
 * Luminance-weighted centroid of the brightest part of an equirectangular sky.
 *
 * Not "the single brightest texel": on a 2K capture that is one pixel of sun
 * core and its position is set as much by sensor noise as by where the sun is.
 * This takes every texel above the horizon carrying more than a fixed fraction
 * of the peak and averages their DIRECTIONS by radiance, which lands on the
 * centre of the solar disc and is stable against a hot cloud edge.
 *
 * Returns null when nothing in the sky is more than a few times the mean —
 * i.e. an overcast or night capture with no sun in it — because rotating an
 * evenly lit dome to align a sun it does not have would be superstition.
 */
function brightestAzimuth(tex: THREE.DataTexture): number | null {
  const img = tex.image as { data: ArrayLike<number>; width: number; height: number };
  const data = img.data;
  const w = img.width;
  const h = img.height;
  if (!data || !w || !h) return null;

  // Peak and mean over the upper hemisphere only.
  let peak = 0;
  let sum = 0;
  let count = 0;
  for (let y = 0; y < h / 2; y++) {
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      const l = 0.2126 * data[o] + 0.7152 * data[o + 1] + 0.0722 * data[o + 2];
      if (l > peak) peak = l;
      sum += l;
      count++;
    }
  }
  const mean = count ? sum / count : 0;
  // A clear sky's sun is orders of magnitude over the mean; an overcast one is
  // under 10x. Below that there is no sun to align.
  if (mean <= 0 || peak / mean < 25) return null;

  const cut = peak * 0.5;
  let vx = 0;
  let vz = 0;
  let wsum = 0;
  for (let y = 0; y < h / 2; y++) {
    const theta = ((y + 0.5) / h) * Math.PI;
    const sy = Math.sin(theta);
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      const l = 0.2126 * data[o] + 0.7152 * data[o + 1] + 0.0722 * data[o + 2];
      if (l < cut) continue;
      // Equirectangular convention matching three's own mapping.
      const phi = ((x + 0.5) / w) * Math.PI * 2;
      vx += Math.sin(phi) * sy * l;
      vz += Math.cos(phi) * sy * l;
      wsum += l;
    }
  }
  if (wsum <= 0) return null;
  return Math.atan2(vx / wsum, vz / wsum);
}

/**
 * Owns the scene's environment map and swaps it when the ambience changes.
 *
 * Holds one generated PMREM target at a time and disposes the previous one,
 * because a session change that leaked a PMREM target per load would quietly
 * eat a few megabytes of VRAM per circuit visited. Loaded HDRIs are cached by
 * name for the lifetime of the renderer instead — there are four of them, they
 * are expensive to filter, and a player moving between sessions revisits the
 * same two.
 */
export class EnvProbe {
  /**
   * False until a captured sky is actually installed. Read by the probe, so
   * that a run which silently fell back cannot be reported as a run that did
   * not — PROJECT.md section 3.2.
   */
  hdriActive = false;
  /** The capture currently installed, for the probe's report. */
  hdriName = '';

  private pmrem: THREE.PMREMGenerator;
  private target: THREE.WebGLRenderTarget | null = null;
  private key = '';
  private readonly hdri = new Map<string, Promise<LoadedHdri | null>>();
  /** The key `apply` was last called with. Guards a late load arriving stale. */
  private wanted = '';

  constructor(renderer: THREE.WebGLRenderer) {
    this.pmrem = new THREE.PMREMGenerator(renderer);
    this.pmrem.compileEquirectangularShader();
  }

  /**
   * Builds the probe for an ambience and applies it to the scene.
   * A repeat call with the same parameters is free.
   *
   * Returns synchronously with the generated probe installed, every time. If a
   * capture for these conditions is on disk it replaces it a few hundred
   * milliseconds later; if it is not, nothing further happens and the scene is
   * lit exactly as it was before issue #78.
   */
  apply(
    scene: THREE.Scene,
    ambience: Ambience,
    wetness: number,
    /**
     * Where the scene's key light stands, in world space. The capture is
     * rotated so its own sun lands here. Omitting it leaves the capture at the
     * orientation it was shot at, which is what the generated probe effectively
     * did and which is the bug described at the top of this file.
     */
    sunPosition?: THREE.Vector3,
  ): void {
    // Quantised, so drizzle drifting from 0.30 to 0.31 does not rebuild and
    // re-filter the probe every frame.
    const w = Math.round(Math.min(1, Math.max(0, wetness)) * 4) / 4;
    const key = `${ambience}:${w}`;
    this.wanted = key;

    if (key !== this.key || !this.target) {
      const src = renderProbe(PALETTES[ambience], w);
      const next = this.pmrem.fromEquirectangular(src);
      src.dispose();
      this.target?.dispose();
      this.target = next;
      this.key = key;
    }

    // The generated probe goes on FIRST and unconditionally. Everything after
    // this point is an upgrade to an image that is already correct.
    scene.environment = this.target!.texture;
    scene.environmentIntensity = 1;
    scene.environmentRotation.set(0, 0, 0);
    this.hdriActive = false;
    this.hdriName = '';

    const wantAzimuth = sunPosition
      ? Math.atan2(sunPosition.x, sunPosition.z)
      : null;

    const set = HDRI_FOR[ambience];
    if (!set) return; // night: the generated probe IS the right answer. See above.
    const name = w >= 0.35 ? set.wet : set.dry;
    void this.load(name).then((loaded) => {
      // A session may have changed circuit, or the weather may have moved,
      // while a 5MB Radiance file was in flight.
      if (!loaded || this.wanted !== key) return;
      scene.environment = loaded.target.texture;
      scene.environmentIntensity = HDRI_INTENSITY[ambience];
      scene.environmentRotation.set(
        0,
        loaded.sunAzimuth === null || wantAzimuth === null
          ? 0
          : wantAzimuth - loaded.sunAzimuth,
        0,
      );
      this.hdriActive = true;
      this.hdriName = name;
    });
  }

  private load(name: string): Promise<LoadedHdri | null> {
    const cached = this.hdri.get(name);
    if (cached) return cached;

    const base = (import.meta as unknown as { env?: { BASE_URL?: string } }).env?.BASE_URL ?? '/';
    const url = `${base}assets/hdri/${name}/${name}.hdr`;

    const job = new Promise<LoadedHdri | null>((resolve) => {
      const loader = new RGBELoader();
      // Full float, not half. The sun direction is found by scanning the
      // texels, and `Uint16Array` half-floats would have to be decoded by hand
      // to do it. The array is discarded immediately after filtering.
      loader.setDataType(THREE.FloatType);
      loader.load(
        url,
        (tex: THREE.DataTexture) => {
          try {
            tex.mapping = THREE.EquirectangularReflectionMapping;
            const sunAzimuth = brightestAzimuth(tex);
            const target = this.pmrem.fromEquirectangular(tex);
            tex.dispose();
            resolve({ target, sunAzimuth });
          } catch {
            resolve(null);
          }
        },
        undefined,
        // The asset directory is gitignored and optional. A 404 is a normal
        // state of this program, not an error, and it must not reach the
        // console as one or every clean clone looks broken.
        () => resolve(null),
      );
    });

    this.hdri.set(name, job);
    return job;
  }

  dispose(): void {
    this.target?.dispose();
    this.target = null;
    for (const job of this.hdri.values()) {
      void job.then((l) => l?.target.dispose());
    }
    this.hdri.clear();
    this.pmrem.dispose();
  }
}
